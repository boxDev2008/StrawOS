#!/bin/bash
set -e
cd "$(dirname "$0")"

NS=lib/netsurf
GEN=obj/nsgen
OBJ=obj/ns

if [ ! -f $GEN/res/Messages ]; then
    TMP=$(mktemp -d)
    trap 'rm -rf "$TMP"' EXIT

    mkdir -p $GEN/libparserutils $GEN/libhubbub/treebuilder $GEN/libcss/parse/properties $GEN/res

    # host-side generators, built with the same clang as everything else
    TOOLS=lib/netsurf-port/tools
    for t in make-aliases make-entities make-element-types; do
        clang -O1 -o $TMP/$t $TOOLS/$t.c
    done
    $TMP/make-aliases $NS/libparserutils/build/Aliases $GEN/libparserutils/aliases.inc
    $TMP/make-entities $NS/libhubbub/build/Entities $GEN/libhubbub/entities.inc
    $TMP/make-element-types $NS/libhubbub/src/treebuilder/element-type.gperf \
        $GEN/libhubbub/treebuilder/autogenerated-element-type.c

    clang -O1 -o $TMP/gen_parser $NS/libcss/src/parse/properties/css_property_parser_gen.c
    grep -E '^[^#][^:]+:' $NS/libcss/src/parse/properties/properties.gen | while IFS= read -r line; do
        name=${line%%:*}
        $TMP/gen_parser -o $GEN/libcss/parse/properties/autogenerated_$name.c "$line"
    done

    # same output as tools/split-messages -l en -p fb, minus its zlib dependency
    awk '/^en\.(all|fb)\.[^:]+:/ {
            sub(/^en\.[a-z]+\./, "")
            k = substr($0, 1, index($0, ":") - 1)
            if (k != prev) n++
            line[n] = $0
            prev = k
        }
        END { for (i = 1; i <= n; i++) print line[i] }' \
        $NS/netsurf/resources/FatMessages > $GEN/res/Messages

    for f in default.css quirks.css adblock.css internal.css netsurf.png favicon.png; do
        cp $NS/netsurf/resources/$f $GEN/res/$f
    done
    cp $NS/netsurf/resources/en/credits.html $NS/netsurf/resources/en/licence.html $GEN/res/
    mkdir -p $GEN/res/icons
    cp $NS/netsurf/resources/icons/*.png $GEN/res/icons/
fi

# copies of the netsurf sources that include <zlib.h>, with the gzip paths stripped
U=$NS/netsurf/utils
GU=$GEN/netsurf/utils
if [ ! -f $GU/hashtable.c ] || [ $U/hashtable.c -nt $GU/hashtable.c ] || [ $U/messages.c -nt $GU/messages.c ]; then
    mkdir -p $GU
    sed '/#include <zlib.h>/d' $U/messages.c > $GU/messages.c
    awk '/#include <zlib.h>/ { next }
         /^\/\*\*$/ { held = $0; next }
         held != "" { if (/compressed memory area/) skip = 1; else print held; held = "" }
         skip { if (/^}$/) skip = 0; next }
         /data\[0\]==0x1f/ { gz = 1 }
         gz { if (/^\t}$/) gz = 0; next }
         { print }' $U/hashtable.c |
        sed -e 's/gzFile fp;.*/FILE *fp;/' -e 's/gzopen(/fopen(/' \
            -e 's/gzgets(fp, s, sizeof s)/fgets(s, sizeof s, fp)/' -e 's/gzclose(/fclose(/' > $GU/hashtable.c
fi

BASE="--target=x86_64-unknown-none -O2 -ffreestanding -nostdlibinc -mno-red-zone -fno-math-errno -fpie -std=gnu99 -w
      -D_GNU_SOURCE -DNDEBUG -Ilib/netsurf-port/include -Ilib/libc/include/posix_compat -Ilib/libc/include
      -include lib/netsurf-port/include/nsconfig.h"

INC_PU="-I$NS/libparserutils/include"
INC_WC="-I$NS/libwapcaplet/include"
INC_CSS="-I$NS/libcss/include"
INC_HB="-I$NS/libhubbub/include"
INC_DOM="-I$NS/libdom/include"
INC_NSU="-I$NS/libnsutils/include"
INC_BMP="-I$NS/libnsbmp/include"
INC_GIF="-I$NS/libnsgif/include"

NS_FLAGS="$INC_PU $INC_WC $INC_CSS $INC_HB $INC_DOM $INC_NSU $INC_BMP $INC_GIF
          -I$NS/netsurf -I$NS/netsurf/include -I$NS/netsurf/content/handlers"

JOBS=()

add() {
    local lib=$1 flags=$2
    shift 2
    mkdir -p $OBJ/$lib
    for src in "$@"; do
        local obj=$OBJ/$lib/$(echo "$src" | tr / _ | sed 's/\.c$/.o/')
        OBJS+=("$obj")
        if [ ! -f "$obj" ] || [ "$src" -nt "$obj" ]; then
            JOBS+=("$src"$'\t'"$obj"$'\t'"$(echo $flags)")
        fi
    done
}

in_dir() {
    local dir=$1
    shift
    for f in "$@"; do echo "$dir/$f"; done
}

OBJS=()

L=$NS/libparserutils/src
add parserutils "$INC_PU -I$L -I$GEN/libparserutils" \
    $(in_dir $L/utils buffer.c errors.c stack.c vector.c) \
    $(in_dir $L/charset aliases.c codec.c) \
    $(in_dir $L/input filter.c inputstream.c) \
    $(in_dir $L/charset/encodings utf8.c utf16.c) \
    $(in_dir $L/charset/codecs codec_ascii.c codec_8859.c codec_ext8.c codec_utf8.c codec_utf16.c)

add wapcaplet "$INC_WC" $NS/libwapcaplet/src/libwapcaplet.c

L=$NS/libcss/src
add css "$INC_PU $INC_WC $INC_CSS -I$L -I$GEN/libcss" \
    $L/stylesheet.c \
    $(in_dir $L/parse parse.c language.c important.c propstrings.c font_face.c mq.c) \
    $L/lex/lex.c \
    $(in_dir $L/utils errors.c utils.c) \
    $L/charset/detect.c \
    $(in_dir $L/select arena.c calc.c computed.c dispatch.c hash.c select.c strings.c font_face.c format_list_style.c unit.c) \
    $(ls $L/parse/properties/*.c | grep -v css_property_parser_gen) \
    $(ls $GEN/libcss/parse/properties/*.c) \
    $(ls $L/select/properties/*.c)

L=$NS/libhubbub/src
add hubbub "$INC_PU $INC_HB -I$L -I$GEN/libhubbub" \
    $L/parser.c \
    $(in_dir $L/utils errors.c string.c) \
    $(ls $L/treebuilder/*.c) \
    $L/charset/detect.c \
    $(in_dir $L/tokeniser entities.c tokeniser.c)

L=$NS/libdom
add dom "$INC_PU $INC_WC $INC_HB $INC_DOM -I$L/src -I$L/include -I$L/bindings" \
    $(ls $L/src/utils/*.c) \
    $(ls $L/src/core/*.c) \
    $(ls $L/src/html/*.c) \
    $(ls $L/src/events/*.c) \
    $L/bindings/hubbub/parser.c

add port "" lib/netsurf-port/port.c

add nsutils "$INC_NSU" $(in_dir $NS/libnsutils/src base64.c time.c unistd.c)
add nsbmp "$INC_BMP" $NS/libnsbmp/src/libnsbmp.c
add nsgif "$INC_GIF" $(in_dir $NS/libnsgif/src gif.c lzw.c)

C=$NS/netsurf
add netsurf "$NS_FLAGS" \
    $(in_dir $C/content content.c content_factory.c fetch.c hlcache.c llcache.c mimesniff.c textsearch.c urldb.c no_backing_store.c) \
    $(in_dir $C/content/fetchers data.c resource.c) \
    $(in_dir $C/content/fetchers/about about.c blank.c certificate.c chart.c choices.c config.c imagecache.c nscolours.c \
        query.c query_auth.c query_fetcherror.c query_privacy.c query_timeout.c testament.c websearch.c) \
    $(in_dir $C/content/fetchers/file dirlist.c file.c) \
    $(in_dir $C/content/handlers/css css.c dump.c internal.c hints.c select.c) \
    $(in_dir $C/content/handlers/html box_construct.c box_inspect.c box_manipulate.c box_normalise.c box_special.c \
        box_textarea.c css.c css_fetcher.c dom_event.c font.c form.c forms.c html.c imagemap.c interaction.c layout.c \
        layout_flex.c object.c redraw.c redraw_border.c script.c table.c textselection.c) \
    $(in_dir $C/content/handlers/image image.c image_cache.c bmp.c gif.c ico.c) \
    $C/content/handlers/text/textplain.c \
    $(in_dir $C/content/handlers/javascript fetcher.c none/none.c) \
    $(in_dir $C/utils bloom.c corestrings.c file.c filepath.c hashmap.c idna.c libdom.c log.c \
        nscolour.c nsoption.c punycode.c ssl_certs.c talloc.c time.c url.c useragent.c utf8.c utils.c) \
    $GU/hashtable.c $GU/messages.c \
    $(in_dir $C/utils/http challenge.c generics.c primitives.c parameter.c cache-control.c content-disposition.c \
        content-type.c strict-transport-security.c www-authenticate.c) \
    $(in_dir $C/utils/nsurl nsurl.c parse.c) \
    $(in_dir $C/desktop cookie_manager.c knockout.c hotlist.c mouse.c plot_style.c print.c search.c searchweb.c \
        scrollbar.c textarea.c version.c system_colour.c local_history.c global_history.c treeview.c page-info.c \
        bitmap.c browser.c browser_window.c browser_history.c download.c frames.c netsurf.c cw_helper.c \
        save_complete.c save_text.c save_pdf.c selection.c textinput.c gui_factory.c)

add frontend "$NS_FLAGS -Ilib/strawx -Ilib/stb -Ilib/net -Isrc/netsurf" \
    $(ls src/netsurf/*.c)

if [ ${#JOBS[@]} -gt 0 ]; then
    printf '%s\n' "${JOBS[@]}" | xargs -d '\n' -P"$(nproc)" -I{} sh -c '
        IFS="	" read -r src obj flags <<EOF
{}
EOF
        eval clang $0 $flags -c "$src" -o "$obj" 2>&1 | grep -E "error" | head -5 | sed "s|^|$src: |"
    ' "$(echo $BASE)"
    rm -f obj/libnetsurf.a
fi

missing=0
for o in "${OBJS[@]}"; do [ -f "$o" ] || missing=$((missing + 1)); done
if [ $missing -gt 0 ]; then
    echo "netsurf: $missing objects failed to build"
    exit 1
fi
if [ ! -f obj/libnetsurf.a ]; then
    llvm-ar rcs obj/libnetsurf.a "${OBJS[@]}"
fi
