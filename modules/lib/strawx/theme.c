const int sx_theme_count = (int)(sizeof(sx_themes) / sizeof(sx_themes[0]));

const SxTheme *sx_theme = &sx_themes[0];

const SxTheme *sx_theme_find(const char *id)
{
    for (int i = 0; i < sx_theme_count; i++)
        if (strcmp(sx_themes[i].id, id) == 0)
            return &sx_themes[i];
    return NULL;
}

void sx_theme_load(void)
{
    char id[32];
    const SxTheme *t = sx_setting_get("theme", id, sizeof(id)) ? sx_theme_find(id) : NULL;
    sx_theme = t ? t : &sx_themes[0];
}
