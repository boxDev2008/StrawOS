// C port of libparserutils/build/make-aliases.pl, so the build needs no perl.
// usage: make-aliases <Aliases> <aliases.inc>

#include <ctype.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define MAX_CANON   512
#define MAX_ALIASES 2048

typedef struct
{
    char *name;
    char *mibenum;
    char *aliases;  // rest of the line, whitespace separated
}
Canon;

typedef struct
{
    char *name;
    int   canon;
}
Alias;

static Canon canons[MAX_CANON];
static int   canon_count;
static Alias aliases[MAX_ALIASES];
static int   alias_count;

static int canon_compare(const void *a, const void *b)
{
    return strcmp(((const Canon *)a)->name, ((const Canon *)b)->name);
}

static int alias_compare(const void *a, const void *b)
{
    return strcmp(((const Alias *)a)->name, ((const Alias *)b)->name);
}

// lowercase and keep only [a-z0-9], as the perl script does
static char *normalise(const char *s)
{
    char *out = malloc(strlen(s) + 1), *p = out;
    for (; *s; s++)
    {
        char c = (char)tolower((unsigned char)*s);
        if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9'))
            *p++ = c;
    }
    *p = '\0';
    return out;
}

static void set_alias(char *name, int canon)
{
    for (int i = 0; i < alias_count; i++)
        if (strcmp(aliases[i].name, name) == 0)
        {
            aliases[i].canon = canon;
            free(name);
            return;
        }
    if (alias_count == MAX_ALIASES)
    {
        fprintf(stderr, "make-aliases: too many aliases\n");
        exit(1);
    }
    aliases[alias_count++] = (Alias){ name, canon };
}

static int is_unicode(const char *name)
{
    if (strncmp(name, "ISO-10646-UCS-", 14) == 0 && (name[14] == '2' || name[14] == '4') && name[15] == '\0')
        return 1;
    return strncmp(name, "UTF-16", 6) == 0 || strcmp(name, "UTF-8") == 0 || strncmp(name, "UTF-32", 6) == 0;
}

int main(int argc, char **argv)
{
    if (argc != 3)
    {
        fprintf(stderr, "usage: make-aliases <Aliases> <aliases.inc>\n");
        return 1;
    }

    FILE *in = fopen(argv[1], "r");
    if (!in)
    {
        perror(argv[1]);
        return 1;
    }

    char line[4096];
    while (fgets(line, sizeof(line), in))
    {
        line[strcspn(line, "\r\n")] = '\0';
        if (line[0] == '#' || line[0] == '\0')
            continue;

        char *rest = line;
        char *name = strsep(&rest, " \t");
        while (rest && isspace((unsigned char)*rest))
            rest++;
        char *mibenum = rest ? strsep(&rest, " \t") : "";
        while (rest && isspace((unsigned char)*rest))
            rest++;

        // a repeated canonical name replaces the earlier entry, like a perl hash
        Canon *c = NULL;
        for (int i = 0; i < canon_count; i++)
            if (strcmp(canons[i].name, name) == 0)
                c = &canons[i];
        if (!c)
        {
            if (canon_count == MAX_CANON)
            {
                fprintf(stderr, "make-aliases: too many charsets\n");
                return 1;
            }
            c = &canons[canon_count++];
            c->name = strdup(name);
        }
        c->mibenum = strdup(mibenum);
        c->aliases = strdup(rest ? rest : "");
    }
    fclose(in);

    qsort(canons, canon_count, sizeof(Canon), canon_compare);

    FILE *out = fopen(argv[2], "w");
    if (!out)
    {
        perror(argv[2]);
        return 1;
    }

    fputs("/*\n"
          " * This file is part of LibParserUtils.\n"
          " * Licensed under the MIT License,\n"
          " *                http://www.opensource.org/licenses/mit-license.php\n"
          " * Copyright 2010 The NetSurf Project.\n"
          " *\n"
          " * Note: This file is automatically generated by make-aliases.pl\n"
          " *\n"
          " * Do not edit file file, changes will be overwritten during build.\n"
          " */\n"
          "\n"
          "static parserutils_charset_aliases_canon canonical_charset_names[] = {\n", out);

    char unicode[4096] = "";
    for (int i = 0; i < canon_count; i++)
    {
        Canon *c = &canons[i];
        fprintf(out, "\t{ %s, %zu, \"%s\" },\n", c->mibenum, strlen(c->name), c->name);

        if (is_unicode(c->name))
        {
            if (unicode[0])
                strcat(unicode, " || ");
            snprintf(unicode + strlen(unicode), sizeof(unicode) - strlen(unicode), "((x) == %s)", c->mibenum);
        }

        set_alias(normalise(c->name), i);
        char *rest = c->aliases, *tok;
        while ((tok = strsep(&rest, " \t")))
            if (*tok)
                set_alias(normalise(tok), i);
    }

    fprintf(out, "};\n\nstatic const uint16_t charset_aliases_canon_count = %d;\n\n", canon_count);
    fputs("typedef struct {\n"
          "\tuint16_t name_len;\n"
          "\tconst char *name;\n"
          "\tparserutils_charset_aliases_canon *canon;\n"
          "} parserutils_charset_aliases_alias;\n"
          "\n"
          "static parserutils_charset_aliases_alias charset_aliases[] = {\n", out);

    qsort(aliases, alias_count, sizeof(Alias), alias_compare);
    for (int i = 0; i < alias_count; i++)
        fprintf(out, "\t{ %zu, \"%s\", &canonical_charset_names[%d] },\n",
                strlen(aliases[i].name), aliases[i].name, aliases[i].canon);

    fprintf(out, "};\n\nstatic const uint16_t charset_aliases_count = %d;\n\n", alias_count);
    fprintf(out, "#define MIBENUM_IS_UNICODE(x) (%s)\n", unicode);
    fclose(out);
    return 0;
}
