// C port of libhubbub/build/make-entities.pl, so the build needs no perl.
// Builds the same ternary search trie of HTML entities.
// usage: make-entities <Entities> <entities.inc>

#include <ctype.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define MAX_NODES 16384

typedef struct
{
    unsigned char pivot;    // 0 marks the end of a key
    int           lt, eq, gt;
    const char   *value;
}
Node;

static Node nodes[MAX_NODES];
static int  node_count;

static int new_node(unsigned char pivot)
{
    if (node_count == MAX_NODES)
    {
        fprintf(stderr, "make-entities: too many trie nodes\n");
        exit(1);
    }
    nodes[node_count] = (Node){ pivot, -1, -1, -1, NULL };
    return node_count++;
}

static int insert(int parent, const unsigned char *key, const char *value)
{
    unsigned char pivot = key[0];
    const unsigned char *tail = pivot ? key + 1 : key;

    if (parent < 0)
        parent = new_node(pivot);

    if (pivot < nodes[parent].pivot)
    {
        int n = insert(nodes[parent].lt, key, value);
        nodes[parent].lt = n;
    }
    else if (pivot == nodes[parent].pivot)
    {
        if (pivot == 0)
            nodes[parent].value = value;
        else
        {
            if (tail[0] == 0)
                nodes[parent].value = value;
            int n = insert(nodes[parent].eq, tail, value);
            nodes[parent].eq = n;
        }
    }
    else
    {
        int n = insert(nodes[parent].gt, key, value);
        nodes[parent].gt = n;
    }
    return parent;
}

int main(int argc, char **argv)
{
    if (argc != 3)
    {
        fprintf(stderr, "usage: make-entities <Entities> <entities.inc>\n");
        return 1;
    }

    FILE *in = fopen(argv[1], "r");
    if (!in)
    {
        perror(argv[1]);
        return 1;
    }

    int root = -1;
    char line[1024];
    while (fgets(line, sizeof(line), in))
    {
        line[strcspn(line, "\r\n")] = '\0';
        if (line[0] == '#' || line[0] == '\0')
            continue;

        char *rest = line;
        char *name = strsep(&rest, " \t");
        while (rest && isspace((unsigned char)*rest))
            rest++;
        char *code = rest ? strsep(&rest, " \t") : NULL;
        if (!code || !*code)
            continue;

        // a repeated entity just overwrites its value, like the perl hash did
        root = insert(root, (const unsigned char *)strdup(name), strdup(code));
    }
    fclose(in);

    FILE *out = fopen(argv[2], "w");
    if (!out)
    {
        perror(argv[2]);
        return 1;
    }

    fputs("/*\n"
          " * This file is part of Hubbub.\n"
          " * Licensed under the MIT License,\n"
          " *                http://www.opensource.org/licenses/mit-license.php\n"
          " * Copyright 2010 The NetSurf Project.\n"
          " *\n"
          " * Note: This file is automatically generated by make-entities.pl\n"
          " *\n"
          " * Do not edit file file, changes will be overwritten during build.\n"
          " */\n"
          "\n"
          "\n"
          "static hubbub_entity_node dict[] = {\n", out);
    for (int i = 0; i < node_count; i++)
        fprintf(out, "\t{ %d, %d, %d, %d, %s },\n", nodes[i].pivot, nodes[i].lt, nodes[i].eq, nodes[i].gt,
                nodes[i].value ? nodes[i].value : "0");
    fprintf(out, "};\n\nstatic int32_t dict_root = %d;\n", root);
    fclose(out);
    return 0;
}
